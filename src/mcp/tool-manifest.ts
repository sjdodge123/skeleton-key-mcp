import type { AppState } from "../app.js";
import type { Target, ToolTier } from "../connectors/types.js";
import { connectorAliases, declaredOptionKeys, listConnectors } from "../connectors/index.js";
import { buildGlobalTools } from "./builtin-tools.js";
import { toolInputJsonSchema } from "./server.js";

/**
 * The committed `tools.manifest.json`: every tool Skeleton Key can expose, with
 * its tier and its input names. It is generated (`npm run manifest`) and a test
 * fails when it is stale, so any new tool, tier change, or new argument shows up
 * as a diff to one maintainer-owned file. That is the review point for the most
 * dangerous kind of change: a state-changing tool declared `read`, which would
 * skip the approval gate.
 *
 * Descriptions are left out on purpose. They change often and carry no security
 * meaning; names, tiers and inputs do.
 */
export interface ToolManifest {
  $comment: string;
  global: ManifestGlobalTool[];
  connectors: Record<string, ManifestConnector>;
}

export interface ManifestTool {
  name: string;
  tier: ToolTier;
  /** Execute tools must build a confirmation string for the approval prompt. */
  confirm: boolean;
  /** Input names; a trailing `?` marks an optional one. */
  inputs: string[];
}

export interface ManifestGlobalTool extends ManifestTool {
  /** Callable while the vault is locked (the kill-switch exempts very few). */
  availableWhenLocked: boolean;
}

export interface ManifestConnector {
  label: string;
  requiresCredential: boolean;
  aliases: string[];
  options: string[] | null;
  snapshot: boolean;
  tools: ManifestTool[];
}

/** Stand-in target used to build a connector's tool list. Tool sets must not
 *  depend on the target (the conformance suite checks that). */
export function placeholderTarget(type: string): Target {
  return { name: "example", type, host: "192.0.2.10" };
}

function inputNames(schema: Parameters<typeof toolInputJsonSchema>[0]): string[] {
  const json = toolInputJsonSchema(schema) as { properties?: Record<string, unknown>; required?: string[] };
  const required = new Set(json.required ?? []);
  return Object.keys(json.properties ?? {}).map((k) => (required.has(k) ? k : `${k}?`));
}

export function buildToolManifest(): ToolManifest {
  // buildGlobalTools only touches `app` inside each tool's run(), so a stub is
  // enough to enumerate the declared tools.
  const global = buildGlobalTools({} as AppState).map((t) => ({
    name: t.name,
    tier: t.tier,
    confirm: typeof t.confirm === "function",
    availableWhenLocked: t.availableWhenLocked ?? false,
    inputs: inputNames(t.inputSchema),
  }));

  const aliases = connectorAliases();
  const connectors: Record<string, ManifestConnector> = {};
  for (const c of [...listConnectors()].sort((a, b) => a.type.localeCompare(b.type))) {
    connectors[c.type] = {
      label: c.label,
      requiresCredential: c.requiresCredential,
      aliases: Object.keys(aliases).filter((a) => aliases[a] === c.type).sort(),
      options: declaredOptionKeys(c),
      snapshot: typeof c.snapshot === "function",
      tools: c.buildTools(placeholderTarget(c.type)).map((t) => ({
        name: t.name,
        tier: t.tier,
        confirm: typeof t.confirm === "function",
        inputs: inputNames(t.inputSchema),
      })),
    };
  }

  return {
    $comment: "Generated by `npm run manifest`. Do not edit by hand; a test fails when this file is stale.",
    global,
    connectors,
  };
}

/** The manifest as committed: stable formatting with a trailing newline. */
export function renderToolManifest(manifest: ToolManifest = buildToolManifest()): string {
  return `${JSON.stringify(manifest, null, 2)}\n`;
}
